// Which body regions each structure belongs to, for proofreading pages and region-limited quizzes.
// Bones belong to the regions they define. Muscles, ligaments, discs and cartilages belong to every region whose defining bones
// they touch inside that region (so a muscle crossing two joints is in both). Nerves belong to the regions holding a fifth of them or more.
// Anything else belongs where its bounds sit inside a region box.
// Usage: node scripts/compute-region-members.mjs   → writes app/region-members.json
import {readFile,writeFile} from 'node:fs/promises';
import * as T from 'three';
import {MeshBVH} from 'three-mesh-bvh';
import {REGIONS,regionBox,regionLandmarks} from '../app/regions.ts';
import {termKey} from '../app/names.ts';
import {loadAtlas,loadGeometry,root} from './lib/atlas-geometry.mjs';

const atlas=await loadAtlas(),geometryOf=await loadGeometry(atlas);
const TOUCH=.004,PAD=.01,MIN_CONTACTS=3,SAMPLES=2500,INSIDE=.5,NERVE_SHARE=.2;
const sideOf=p=>/\bleft\b/i.test(p.name)?'left':/\bright\b/i.test(p.name)?'right':null;
const bvhs=new Map();
const bvhOf=p=>{let b=bvhs.get(p.id);if(!b){const g=geometryOf(p),geometry=new T.BufferGeometry();geometry.setAttribute('position',new T.BufferAttribute(g.position,3));geometry.setIndex(new T.BufferAttribute(g.index,1));b=new MeshBVH(geometry);bvhs.set(p.id,b);}return b;};
const within=(point,box,pad)=>point.every((v,i)=>v>=box[0][i]-pad&&v<=box[1][i]+pad);
const near=(a,b,pad)=>a[0].every((v,i)=>v<=b[1][i]+pad&&a[1][i]>=b[0][i]-pad);
const overlap=(b,box)=>{let v=1,own=1;for(let i=0;i<3;i++){v*=Math.max(0,Math.min(b[1][i],box[1][i])-Math.max(b[0][i],box[0][i]));own*=Math.max(1e-9,b[1][i]-b[0][i]);}return v/own;};

// Every region on each side: its box and its landmark bones (with the counted part of each bone).
const regions=[];
for(const r of REGIONS)for(const side of r.sided?['left','right']:[null]){
 const box=regionBox(atlas,r.id,side??'right');if(!box)continue;
 regions.push({id:r.id,side,box,landmarks:regionLandmarks(atlas,r.id,side??'right')});
}
const sideMatches=(p,region)=>!region.side||!sideOf(p)||sideOf(p)===region.side;
const landmarkBones=new Set(regions.flatMap(r=>r.landmarks.map(l=>l.part)));
// Textbook region membership the bone contacts miss (sternocleidomastoid attaches above and below the cervical spine).
const {add}=JSON.parse(await readFile(new URL('scripts/region-member-overrides.json',root),'utf8'));
const members={},point=new T.Vector3(),target={};
for(const p of atlas.parts){
 const found=new Set();
 if(landmarkBones.has(p)){for(const r of regions)if(sideMatches(p,r)&&r.landmarks.some(l=>l.part===p))found.add(r.id);}
 // Muscles, ligaments, fasciae, discs and cartilages: the regions whose defining bones they touch.
 else if(['skeletal','muscular','connective','fascia'].includes(p.system)){
  const candidates=[];for(const r of regions)if(sideMatches(p,r))for(const l of r.landmarks)if(near(p.bounds,l.box,PAD+TOUCH))candidates.push({region:r,landmark:l});
  if(candidates.length){
   const g=geometryOf(p),step=Math.max(1,Math.floor(p.vertexCount/SAMPLES)),counts=new Map();
   for(let v=0;v<p.vertexCount;v+=step){
    point.fromArray(g.position,v*3);const xyz=[point.x,point.y,point.z];
    for(const {region,landmark} of candidates){
     if(!within(xyz,landmark.box,PAD))continue;
     if(bvhOf(landmark.part).closestPointToPoint(point,target,0,TOUCH))counts.set(region.id,(counts.get(region.id)??0)+1);
    }
   }
   for(const [id,n] of counts)if(n>=MIN_CONTACTS)found.add(id);
  }
 }
 // Peripheral nerves run through several regions without attaching to bone: a nerve belongs where a fifth of it lies or more.
 else if(p.system==='nervous'){
  const g=geometryOf(p),step=Math.max(1,Math.floor(p.vertexCount/SAMPLES)),samples=Math.ceil(p.vertexCount/step);
  for(const r of regions){
   if(!sideMatches(p,r)||!near(p.bounds,r.box,0))continue;
   let n=0;for(let v=0;v<p.vertexCount;v+=step)if(within([g.position[v*3],g.position[v*3+1],g.position[v*3+2]],r.box,0))n++;
   if(n/samples>=NERVE_SHARE)found.add(r.id);
  }
 }
 // Structures without a bony attachment found above fall back to where they sit.
 if(!found.size)for(const r of regions)if(sideMatches(p,r)&&overlap(p.bounds,r.box)>=INSIDE)found.add(r.id);
 for(const id of add[termKey(p.name)]??[])found.add(id);
 if(found.size)members[p.id]=REGIONS.map(r=>r.id).filter(id=>found.has(id));
}
const unknown=Object.keys(add).filter(k=>!atlas.parts.some(p=>termKey(p.name)===k));
if(unknown.length)throw new Error(`Region overrides name structures that are not in the atlas: ${unknown.join(', ')}`);
const counts=Object.fromEntries(REGIONS.map(r=>[r.id,Object.values(members).filter(m=>m.includes(r.id)).length]));
await writeFile(new URL('app/region-members.json',root),JSON.stringify({note:'Generated by scripts/compute-region-members.mjs: part id → regions it belongs to (the side is the part\'s own).',members},null,0)+'\n');
console.log(`Region members: ${Object.keys(members).length} of ${atlas.parts.length} parts in a region; per region ${JSON.stringify(counts)}`);
